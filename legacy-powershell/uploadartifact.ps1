        $EncodedFileContent = [Convert]::ToBase64String($FileBytes)

       


        

        # ** Construct API Request Body **
        $Body = @{
            "Name"            = $CurrentArtifactName
            "ArtifactContent" = $EncodedFileContent
        } | ConvertTo-Json -Depth 3

        # ** Send Import Request **
        Write-Host "🚀 Sending Upload Request to: $Url"
        Invoke-RestMethod -Uri $Url -Headers $Headers -Method PUT -Body $Body -ContentType "application/json"

        Write-Host "✅ Successfully Uploaded Artifact: $CurrentArtifactName to Package: $PackageId"

        return @{
            Status  = "success"
            Message = "Artifact uploaded successfully!"
            TargetArtifactId = $ArtifactId  # Send back new Artifact ID
            #TargetPackageId  = $PackageId
        }
    }
    catch {
        Write-Host "❌ Upload Failed: $_"
        return @{
            Status  = "error"
            Message = "Failed to upload artifact"
        }
    }


